import { test, expect, _electron as electron, type ElectronApplication, type Page } from '@playwright/test'
import { createServer, type Server } from 'node:http'
import { mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

let instance: ElectronApplication, page: Page, server: Server, directory: string, audioUrl: string
test.describe.configure({ mode: 'serial' })
async function launch() {
  const env: Record<string, string> = { ...process.env, CLOUD_MUSIC_TEST: '1', CLOUD_MUSIC_TEST_DIR: directory, CLOUD_MUSIC_TEST_URL: audioUrl }
  delete env.ELECTRON_RUN_AS_NODE
  instance = await electron.launch({ args: [resolve('out/main/index.js'), '--no-sandbox', '--disable-gpu', '--ozone-platform=headless', '--password-store=basic'], env })
  page = await instance.firstWindow()
  await expect(page.locator('.app-shell')).toBeVisible()
  await instance.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1000, 680))
  await page.emulateMedia({ reducedMotion: 'reduce' })
}
const bootstrap = () => page.evaluate(async () => {
  const result = await window.music.invoke('app.bootstrap')
  if (!result.ok) throw new Error(result.error.message)
  return result.data
})
test.beforeAll(async () => {
  directory = await mkdtemp(join(tmpdir(), 'libitum-eq-graph-'))
  const audio = Buffer.alloc(44 + 48000 * 2 * 60)
  audio.write('RIFF'); audio.writeUInt32LE(audio.length - 8, 4); audio.write('WAVEfmt ', 8); audio.writeUInt32LE(16, 16); audio.writeUInt16LE(1, 20); audio.writeUInt16LE(1, 22); audio.writeUInt32LE(48000, 24); audio.writeUInt32LE(96000, 28); audio.writeUInt16LE(2, 32); audio.writeUInt16LE(16, 34); audio.write('data', 36); audio.writeUInt32LE(audio.length - 44, 40)
  server = createServer((_, res) => { res.writeHead(200, { 'Content-Type': 'audio/wav', 'Content-Length': audio.length }); res.end(audio) })
  await new Promise<void>(done => server.listen(0, '127.0.0.1', done))
  audioUrl = `http://127.0.0.1:${(server.address() as any).port}/audio.wav`
  await launch()
  await page.evaluate(() => window.music.invoke('auth.importCookie', { provider: 'netease', cookie: 'MUSIC_U=fixture' }))
  await page.getByLabel('搜索音乐').fill('晚风'); await page.getByLabel('搜索音乐').press('Enter')
  await page.getByRole('button', { name: '播放 晚风经过', exact: true }).click()
  await page.getByRole('button', { name: '暂停播放', exact: true }).click()
  await expect.poll(async () => (await bootstrap()).player.status).toBe('paused')
  await page.evaluate(() => window.music.invoke('player.seek', { seconds: 7 }))
  // Let mpv's observed time replace the optimistic seek position before comparing.
  await page.waitForTimeout(250)
  expect((await bootstrap()).player.position).toBeGreaterThan(6.5)
})
test.afterAll(async () => {
  if (instance) await instance.close()
  if (server) await new Promise<void>(done => server.close(() => done()))
  if (directory) await rm(directory, { recursive: true, force: true })
})

test('drags graph handles, synchronizes controls, and applies without restarting audio', async () => {
  const before = await bootstrap()
  await page.locator('.playback-options').getByRole('button', { name: '十段 PEQ', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '十段参数均衡器' })
  await expect(dialog.getByRole('group', { name: 'EQ 频响图', exact: true })).toBeVisible()
  await dialog.getByLabel('启用十段 PEQ', { exact: true }).check()
  const initialPath = await dialog.locator('.peq-total-curve').getAttribute('d')
  const point = dialog.getByRole('button', { name: '第 6 段控制点', exact: true })
  const box = (await point.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down()
  const target = await dialog.locator('svg.peq-plot').evaluate((svg: SVGSVGElement) => {
    const p = new DOMPoint(48 + Math.log10(1500 / 20) / 3 * 648, 20 + (24 - 6) / 48 * 224).matrixTransform(svg.getScreenCTM()!)
    return { x: p.x, y: p.y }
  })
  await page.mouse.move(target.x, target.y, { steps: 10 }); await page.mouse.up()
  await expect(dialog.getByLabel('选中频段频率', { exact: true })).toHaveValue('1500')
  await expect(dialog.getByLabel('选中频段增益', { exact: true })).toHaveValue('6')
  expect(await dialog.locator('.peq-total-curve').getAttribute('d')).not.toBe(initialPath)
  await point.focus(); await page.keyboard.press('ArrowUp')
  await expect(dialog.getByLabel('选中频段增益', { exact: true })).toHaveValue('6.1')
  await page.keyboard.press('Shift+ArrowRight')
  await expect(dialog.getByLabel('选中频段频率', { exact: true })).toHaveValue('1890')
  await page.keyboard.press('Home')
  await expect(dialog.getByLabel('选中频段增益', { exact: true })).toHaveValue('0')
  await dialog.getByLabel('选中频段增益', { exact: true }).focus(); await page.keyboard.press('End')
  await expect(dialog.getByLabel('选中频段增益', { exact: true })).toHaveValue('24')
  await dialog.getByLabel('选中频段 Q', { exact: true }).focus(); await page.keyboard.press('End')
  await expect(dialog.getByLabel('选中频段 Q', { exact: true })).toHaveValue('20')
  // Pointer capture must continue dragging outside the SVG, with legal values.
  await point.scrollIntoViewIfNeeded()
  const edgeBox = (await point.boundingBox())!, plotBox = (await dialog.locator('svg.peq-plot').boundingBox())!
  await page.mouse.move(edgeBox.x + edgeBox.width / 2, edgeBox.y + edgeBox.height / 2); await page.mouse.down()
  await page.mouse.move(plotBox.x + plotBox.width + 12, plotBox.y - 12, { steps: 5 }); await page.mouse.up()
  await expect(dialog.getByLabel('选中频段频率', { exact: true })).toHaveValue('20000')
  await expect(dialog.getByLabel('选中频段增益', { exact: true })).toHaveValue('24')
  await dialog.getByText('精确参数 · 全部十段', { exact: true }).click()
  await expect(dialog.getByLabel('第 6 段频率', { exact: true })).toHaveValue('20000')
  await expect(dialog.getByLabel('第 6 段 Q', { exact: true })).toHaveValue('20')
  await dialog.getByLabel('第 6 段增益', { exact: true }).fill('-3')
  await expect(dialog.getByLabel('选中频段增益', { exact: true })).toHaveValue('-3')
  await dialog.getByLabel('第 6 段 Q', { exact: true }).fill('1.4')
  await dialog.getByLabel('PEQ 前级增益', { exact: true }).fill('-4')
  await expect(dialog.getByLabel('前级增益滑杆', { exact: true })).toHaveValue('-4')
  expect((await bootstrap()).settings.peq.enabled).toBe(false)
  await dialog.getByLabel('第 6 段频率', { exact: true }).fill('19')
  await expect(dialog.getByRole('button', { name: '应用 PEQ', exact: true })).toBeDisabled()
  await dialog.getByLabel('第 6 段频率', { exact: true }).fill('1890')
  await dialog.getByText('精确参数 · 全部十段', { exact: true }).click()
  await dialog.getByRole('button', { name: '应用 PEQ', exact: true }).click()
  await expect.poll(async () => (await bootstrap()).settings.peq.bands[5].gain).toBe(-3)
  const after = await bootstrap()
  expect(after.player.status).toBe('paused')
  expect(Math.abs(after.player.position - before.player.position)).toBeLessThan(0.1)
  expect(after.settings.peq.preamp).toBe(-4)
  await expect(dialog.getByText('已应用', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '关闭对话框', exact: true }).click()
})

test('previews imported presets and bypass without losing saved settings on cancel', async () => {
  await page.locator('.playback-options').getByRole('button', { name: '十段 PEQ', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '十段参数均衡器' })
  const preset = join(directory, 'peq.txt')
  await writeFile(preset, 'Preamp: -6 dB\nFilter 1: ON LS Fc 105 Hz Gain 3 dB Q 0.71\nFilter 2: OFF PK Fc 1000 Hz Gain -6 dB Q 2\n')
  await instance.evaluate(({ dialog }, path) => { (dialog as any).showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, preset)
  await dialog.getByRole('button', { name: '导入 TXT', exact: true }).click()
  await expect(dialog.getByText('已载入预览，尚未应用到播放。', { exact: true })).toBeVisible()
  await expect(dialog.getByLabel('选中频段类型', { exact: true })).toHaveValue('LS')
  await expect(dialog.getByLabel('选中频段频率', { exact: true })).toHaveValue('105')
  const path = await dialog.locator('.peq-total-curve').getAttribute('d')
  await dialog.getByRole('button', { name: '选择第 2 段', exact: true }).click()
  await expect(dialog.getByLabel('启用选中频段', { exact: true })).not.toBeChecked()
  await dialog.getByLabel('启用选中频段', { exact: true }).check()
  expect(await dialog.locator('.peq-total-curve').getAttribute('d')).not.toBe(path)
  await dialog.getByLabel('启用十段 PEQ', { exact: true }).uncheck()
  await expect(dialog.getByText('总开关已关闭 · 仅预览', { exact: true })).toBeVisible()
  await writeFile(preset, 'Filter 1: ON PK Fc 1 Hz Gain 50 dB Q 0\n')
  await dialog.getByRole('button', { name: '导入 TXT', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('参数超出范围')
  await expect(dialog.getByLabel('选中频段增益', { exact: true })).toHaveValue('-6')
  await instance.evaluate(({ dialog }) => { (dialog as any).showOpenDialog = async () => ({ canceled: true, filePaths: [] }) })
  await dialog.getByRole('button', { name: '导入 TXT', exact: true }).click()
  await expect(dialog.getByLabel('选中频段增益', { exact: true })).toHaveValue('-6')
  await dialog.getByRole('button', { name: '重置预览', exact: true }).click()
  await expect(dialog.getByLabel('选中频段频率', { exact: true })).toHaveValue('31')
  await dialog.getByRole('button', { name: '关闭对话框', exact: true }).click()
  expect((await bootstrap()).settings.peq.bands[5].gain).toBe(-3)
})

test('restores applied EQ after restart and shares the graph with settings in both themes', async () => {
  await instance.close(); await launch()
  expect((await bootstrap()).settings.peq.bands[5]).toMatchObject({ frequency: 1890, gain: -3, q: 1.4 })
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('button', { name: '音效', exact: true }).click()
  await expect(page.getByRole('group', { name: 'EQ 频响图', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '选择第 6 段', exact: true }).click()
  await expect(page.getByLabel('选中频段频率', { exact: true })).toHaveValue('1890')
  const status = (await bootstrap()).player.status
  await page.getByRole('button', { name: '第 6 段控制点', exact: true }).focus()
  await page.keyboard.press('Space')
  expect((await bootstrap()).player.status).toBe(status)
  await page.getByLabel('选中频段频率', { exact: true }).fill('2000')
  await page.evaluate(() => window.music.invoke('settings.update', { theme: 'dark' }))
  await expect(page.getByLabel('选中频段频率', { exact: true })).toHaveValue('2000')
  expect(await page.locator('.peq-graph').evaluate(e => e.scrollWidth <= e.clientWidth + 1)).toBe(true)
  await page.screenshot({ path: 'test-results/peq-graph-dark.png', animations: 'disabled' })
  await page.evaluate(() => window.music.invoke('settings.update', { theme: 'light' }))
  await page.screenshot({ path: 'test-results/peq-graph-light.png', animations: 'disabled' })
})
